/** id → 展示名；未收录的 id 以英文 id 规范化后回退，避免出现下划线形式 */
export function symbolName(id: string): string {
  const hit = SYMBOL_NAMES[id] ?? ITEM_NAMES[id];
  if (hit) return hit;
  // 精华沿用本体的名字：pink_pepper_essence → 粉胡椒精华
  if (id.endsWith('_essence')) {
    const base = id.slice(0, -'_essence'.length);
    const baseName = SYMBOL_NAMES[base] ?? ITEM_NAMES[base];
    if (baseName) return `${baseName}精华`;
  }
  return id
    .split('_')
    .filter(Boolean)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ');
}

/**
 * 原作里这个 id 自带的英文名（chili_powder → Chili Powder）。
 * 我们换过图标与中文名，邮件里用「中文名(英文名)」的形式标出对照关系。
 */
export function literalName(id: string): string {
  const base = id.endsWith('_essence') ? id.slice(0, -'_essence'.length) : id;
  const words = base
    .split('_')
    .filter(Boolean)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ');
  return id.endsWith('_essence') ? `${words} Essence` : words;
}

/** 中文展示名 + 原作英文名：辣椒(Chili Powder) */
export function bilingualName(id: string): string {
  const cn = symbolName(id);
  const en = literalName(id);
  return cn === en ? cn : `${cn}(${en})`;
}

export function groupName(id: string): string {
  return GROUP_NAMES[id] ?? id;
}

/** 详情面板里「组：a / b」用 */
export function groupList(groups: readonly string[] | undefined): string {
  if (!groups || groups.length === 0) return '—';
  return groups.map(groupName).join(' / ');
}
