const GROUP_FALLBACK: Array<[string, string]> = [
  ['animal', '🐾'],
  ['organism', '🧬'],
  ['human', '🧑'],
  ['food', '🍽️'],
  ['fruit', '🍎'],
  ['drink', '🥤'],
  ['booze', '🍺'],
  ['gem', '💎'],
  ['plant', '🌿'],
  ['ore', '🪨'],
  ['card', '🃏'],
  ['dice', '🎲'],
  ['pirate', '🏴‍☠️'],
  ['hex', '🧿'],
  ['capsule', '🧪'],
];

export function emojiOf(def: SymbolDef | null | undefined): string {
  if (!def) return '';
  const direct = EMOJI[def.id];
  if (direct) return direct;
  const item = ITEM_EMOJI[def.id];
  if (item) return item;
  // 精华没有独立图标：改用本体图标，避免整片「显示不出来」
  if (def.id.endsWith('_essence')) {
    const base = def.id.slice(0, -'_essence'.length);
    const hit = EMOJI[base] ?? ITEM_EMOJI[base];
    if (hit) return hit;
  }
  if (def.id.startsWith('matryoshka')) return '🪆';
  if (def.id.startsWith('hex_of')) return '🧿';
  if (def.id.startsWith('dice') || /^d\d/.test(def.id)) return '🎲';
  for (const [group, emoji] of GROUP_FALLBACK) {
    if ((def.groups ?? []).includes(group)) return emoji;
  }
  return '❔';
}

